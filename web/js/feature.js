function physicsTimelineToScrollTimeline(physicsTimeline, pixelsPerUnit) {
  return physicsTimeline.filter(pt => !pt.emittedH).map(pt => ({
    timeMs: pt.timeMs,
    scrollTop: pt.totalDelta * pixelsPerUnit,
  }));
}

function physicsTimelineToHorizontalScrollTimeline(physicsTimeline, pixelsPerUnit) {
  return physicsTimeline.filter(pt => pt.emittedH || pt.totalDeltaH > 0).map(pt => ({
    timeMs: pt.timeMs,
    scrollLeft: (pt.totalDeltaH || 0) * pixelsPerUnit,
  }));
}

function mergeScrollTimelines(verticalTl, horizontalTl) {
  const byTime = new Map();
  for (const pt of verticalTl) {
    byTime.set(pt.timeMs, { ...(byTime.get(pt.timeMs) || {}), timeMs: pt.timeMs, scrollTop: pt.scrollTop });
  }
  for (const pt of horizontalTl) {
    byTime.set(pt.timeMs, { ...(byTime.get(pt.timeMs) || {}), timeMs: pt.timeMs, scrollLeft: pt.scrollLeft });
  }

  let scrollTop = 0;
  let scrollLeft = 0;
  return Array.from(byTime.values())
    .sort((a, b) => a.timeMs - b.timeMs)
    .map(pt => {
      if (pt.scrollTop != null) scrollTop = pt.scrollTop;
      if (pt.scrollLeft != null) scrollLeft = pt.scrollLeft;
      return { timeMs: pt.timeMs, scrollTop, scrollLeft };
    });
}

function generateOffTimeline(scenario, pixelsPerUnit) {
  const timeline = [];
  let totalDelta = 0;
  for (const evt of scenario.events) {
    totalDelta += 120;
    timeline.push({ timeMs: evt.timeMs, scrollTop: totalDelta * pixelsPerUnit });
  }
  // Hold the final position. No deceleration for "OFF" mode.
  if (timeline.length > 0) {
    const lastTime = timeline[timeline.length - 1].timeMs;
    const lastScrollTop = timeline[timeline.length - 1].scrollTop;
    timeline.push({ timeMs: lastTime + 500, scrollTop: lastScrollTop });
  }
  return timeline;
}

// Looping auto-play on visibility.

class LoopingAutoPlay {
  constructor() {
    this._callbacks = new Map();
    this._visible = new Set();
    this._observer = new IntersectionObserver((entries) => {
      for (const entry of entries) {
        const el = entry.target;
        if (entry.isIntersecting) {
          if (!this._visible.has(el)) {
            this._visible.add(el);
            this._start(el);
          }
        } else {
          this._visible.delete(el);
          this._stop(el);
        }
      }
    }, { threshold: 0.3 });
  }

  observe(sectionEl, callback) {
    this._callbacks.set(sectionEl, callback);
    this._observer.observe(sectionEl);
  }

  _start(el) {
    const cb = this._callbacks.get(el);
    if (cb) cb();
  }

  _stop(el) {
    const cb = this._callbacks.get(el);
    if (cb && cb._stop) cb._stop();
  }

  disconnect() {
    this._observer.disconnect();
  }
}

