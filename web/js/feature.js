// ScrollDemo component.

class ScrollDemo {
  constructor(container, options) {
    this.container = container;
    this.timeline = options.timeline;
    this.totalMs = options.totalMs;
    this.hasHorizontalScroll = options.hasHorizontalScroll || false;
    this.onProgress = options.onProgress || null;
    this._animFrame = null;
    this._startTime = 0;

    this._build(options.sourceCode);
  }

  _build(sourceCode) {
    this.container.innerHTML = '';

    const content = document.createElement('div');
    content.className = 'demo-box-content' + (this.hasHorizontalScroll ? ' has-horizontal-scroll' : '');

    const pre = document.createElement('pre');
    pre.innerHTML = renderCodeWithLineNumbers(sourceCode);
    content.appendChild(pre);
    this.container.appendChild(content);

    this._content = content;
  }

  play() {
    if (prefersReducedMotion()) {
      const last = this.timeline[this.timeline.length - 1];
      this._content.scrollTop = last.scrollTop;
      this._content.scrollLeft = last.scrollLeft || 0;
      if (this.onProgress) this.onProgress(this.totalMs);
      return;
    }

    this._startTime = performance.now();
    this._animFrame = requestAnimationFrame(this._animate.bind(this));
  }

  stop() {
    if (this._animFrame) {
      cancelAnimationFrame(this._animFrame);
      this._animFrame = null;
    }
    this._content.scrollTop = 0;
    this._content.scrollLeft = 0;
  }

  _animate(now) {
    const elapsed = now - this._startTime;
    const tl = this.timeline;
    const totalMs = this.totalMs;

    // Loop: wrap elapsed time
    const loopElapsed = elapsed % totalMs;

    // Find bracketing entries
    let i = 0;
    while (i < tl.length - 1 && tl[i + 1].timeMs <= loopElapsed) i++;

    if (i >= tl.length - 1) {
      const last = tl[tl.length - 1];
      this._content.scrollTop = last.scrollTop;
      if (last.scrollLeft != null) this._content.scrollLeft = last.scrollLeft;
      if (this.onProgress) this.onProgress(loopElapsed);
      this._animFrame = requestAnimationFrame(this._animate.bind(this));
      return;
    }

    const a = tl[i];
    const b = tl[i + 1];
    const t = (loopElapsed - a.timeMs) / (b.timeMs - a.timeMs);

    this._content.scrollTop = a.scrollTop + (b.scrollTop - a.scrollTop) * t;
    const scrollLeftA = a.scrollLeft || 0;
    const scrollLeftB = b.scrollLeft || 0;
    this._content.scrollLeft = scrollLeftA + (scrollLeftB - scrollLeftA) * t;

    if (this.onProgress) this.onProgress(loopElapsed);
    this._animFrame = requestAnimationFrame(this._animate.bind(this));
  }
}

