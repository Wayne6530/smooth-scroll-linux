// AdaptiveCycler cycles through speed adaptive scenarios one at a time.

class AdaptiveCycler {
  constructor(containerEl, scenarios, defaultOptions, pixelsPerUnit) {
    this.containerEl = containerEl;
    this.scenarios = scenarios;
    this.currentIndex = 0;
    this._animFrame = null;
    this._startTime = 0;
    this._content = null;
    this._timelineInstance = null;

    // Pre-compute all scenario data
    this.scenarioData = scenarios.map(({ key, scenario, i18nKey }) => {
      const result = PhysicsEngine.simulate(defaultOptions, scenario,
        { events: buildFeatureEvents(scenario) });
      const { timeline: paddedTl, totalMs } = buildPaddedTimeline(
        result.timeline, scenario, pixelsPerUnit);
      const events = buildPaddedTimelineEvents(scenario);

      const lastPt = result.timeline.length > 0 ? result.timeline[result.timeline.length - 1] : null;
      const totalDistance = lastPt ? lastPt.totalDelta : 0;
      const eventCount = scenario.events.length;
      const avgDistance = eventCount > 0 ? Math.round(totalDistance / eventCount) : 0;

      return { key, scenario, i18nKey, paddedTl, totalMs, events, result, totalDistance, eventCount, avgDistance };
    });

    this._buildDemoBox();
    this._populateDataPanel();
    this._switchTo(0);
  }

  _buildDemoBox() {
    this.containerEl.innerHTML = '';
    const content = document.createElement('div');
    content.className = 'demo-box-content';
    const pre = document.createElement('pre');
    pre.innerHTML = renderCodeWithLineNumbers(DEMO_SOURCE.vertical);
    content.appendChild(pre);
    this.containerEl.appendChild(content);
    this._content = content;
  }

  _populateDataPanel() {
    for (const data of this.scenarioData) {
      document.getElementById(`adaptive-dist-${data.key}`).textContent = data.totalDistance;
      document.getElementById(`adaptive-events-${data.key}`).textContent = data.eventCount;
      document.getElementById(`adaptive-avg-${data.key}`).textContent = data.avgDistance;
    }
  }

  _switchTo(index) {
    this.currentIndex = index;
    const data = this.scenarioData[index];
    this._timelineInstance = new DemoTimeline('timeline-adaptive', data.events, data.totalMs);
    this._updateFocus();
  }

  _updateFocus() {
    const rows = document.querySelectorAll('.adaptive-data-row:not(.adaptive-data-header)');
    rows.forEach((row, i) => {
      row.classList.toggle('focused', i === this.currentIndex);
    });

    const label = document.getElementById('adaptive-demo-label');
    const i18nKey = this.scenarioData[this.currentIndex].i18nKey;
    label.setAttribute('data-i18n', i18nKey);
    label.textContent = I18n.t(i18nKey);
  }

  play() {
    if (prefersReducedMotion()) {
      this._switchTo(this.currentIndex);
      const data = this.scenarioData[this.currentIndex];
      const last = data.paddedTl[data.paddedTl.length - 1];
      if (last) this._content.scrollTop = last.scrollTop;
      if (this._timelineInstance) this._timelineInstance.setProgress(data.totalMs);
      return;
    }

    this._switchTo(this.currentIndex);
    this._startTime = performance.now();
    this._animFrame = requestAnimationFrame(this._animate.bind(this));
  }

  stop() {
    if (this._animFrame) {
      cancelAnimationFrame(this._animFrame);
      this._animFrame = null;
    }
    if (this._content) this._content.scrollTop = 0;
  }

  _animate(now) {
    const elapsed = now - this._startTime;
    const data = this.scenarioData[this.currentIndex];
    const tl = data.paddedTl;
    const totalMs = data.totalMs;

    if (elapsed >= totalMs) {
      this._content.scrollTop = 0;
      this._switchTo((this.currentIndex + 1) % this.scenarios.length);
      this._startTime = performance.now();
      this._animFrame = requestAnimationFrame(this._animate.bind(this));
      return;
    }

    let i = 0;
    while (i < tl.length - 1 && tl[i + 1].timeMs <= elapsed) i++;

    if (i >= tl.length - 1) {
      const last = tl[tl.length - 1];
      this._content.scrollTop = last.scrollTop;
    } else {
      const a = tl[i];
      const b = tl[i + 1];
      const t = (elapsed - a.timeMs) / (b.timeMs - a.timeMs);
      this._content.scrollTop = a.scrollTop + (b.scrollTop - a.scrollTop) * t;
    }

    if (this._timelineInstance) this._timelineInstance.setProgress(elapsed);

    this._animFrame = requestAnimationFrame(this._animate.bind(this));
  }

}

function renderCodeWithLineNumbers(code) {
  const lines = code.split('\n');
  return lines.map((line, i) =>
    `<span class="line-number">${i + 1}</span>${escapeHtml(line)}`
  ).join('\n');
}

function escapeHtml(str) {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

