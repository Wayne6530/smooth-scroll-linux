// Section indicator.

function initSectionIndicator() {
  const indicator = document.getElementById('section-indicator');
  const pips = indicator.querySelectorAll('.section-pip');
  const sections = document.querySelectorAll('.feature-section');

  let activeIdx = 0;

  const sectionObserver = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
      }
      if (entry.isIntersecting) {
        const idx = Array.from(sections).indexOf(entry.target);
        activeIdx = idx;
        pips.forEach((p, i) => p.classList.toggle('active', i === idx));
      }
    }
  }, { threshold: 0.4 });

  sections.forEach(s => sectionObserver.observe(s));

  pips.forEach(pip => {
    pip.addEventListener('click', (e) => {
      e.preventDefault();
      const target = document.querySelector(pip.getAttribute('href'));
      if (target) target.scrollIntoView({ behavior: 'smooth' });
    });
  });

  document.addEventListener('keydown', (e) => {
    if (e.key !== 'ArrowDown' && e.key !== 'ArrowUp') return;
    if (e.target.closest('input, textarea, select, [contenteditable]')) return;

    e.preventDefault();
    let nextIdx;
    if (e.key === 'ArrowDown') {
      nextIdx = Math.min(activeIdx + 1, sections.length - 1);
    } else {
      nextIdx = Math.max(activeIdx - 1, 0);
    }
    if (nextIdx !== activeIdx) {
      sections[nextIdx].scrollIntoView({ behavior: 'smooth' });
    }
  });
}

