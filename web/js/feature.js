// Helpers.

function buildFeatureEvents(scenario) {
  // Only build feature-specific events (free-spin, drag-view, mouse movements).
  // Scroll events from scenario.events are already handled by PhysicsEngine.simulate.
  const events = [];

  if (scenario.freeSpinStartMs != null) {
    events.push({ timeUs: scenario.freeSpinStartMs * 1000, type: 'free-spin', value: 1 });
  }
  if (scenario.freeSpinEndMs != null) {
    events.push({ timeUs: scenario.freeSpinEndMs * 1000, type: 'free-spin', value: 0 });
  }
  if (scenario.dragViewPressMs != null) {
    events.push({ timeUs: scenario.dragViewPressMs * 1000, type: 'drag-view', value: 1 });
  }
  if (scenario.dragViewReleaseMs != null) {
    events.push({ timeUs: scenario.dragViewReleaseMs * 1000, type: 'drag-view', value: 0 });
  }
  if (scenario.mouseMovements) {
    for (const m of scenario.mouseMovements) {
      if (m.relX != null && m.relX !== 0) {
        events.push({ timeUs: m.timeMs * 1000, type: 'rel-x', value: m.relX });
      }
      if (m.relY != null && m.relY !== 0) {
        events.push({ timeUs: m.timeMs * 1000, type: 'rel-y', value: m.relY });
      }
    }
  }

  return events.sort((a, b) => a.timeUs - b.timeUs);
}

function buildPaddedTimeline(physicsTimelineOrRaw, scenario, pixelsPerUnit) {
  const enterDelay = scenario.enterDelayMs || 0;
  const pause = scenario.pauseMs || 0;

  // Accept either physics timeline (array of objects) or pre-built scroll timeline
  let verticalTl, horizontalTl;
  if (physicsTimelineOrRaw.length > 0 && physicsTimelineOrRaw[0].scrollTop != null) {
    // Already a scroll timeline
    verticalTl = physicsTimelineOrRaw;
    horizontalTl = [];
  } else {
    verticalTl = physicsTimelineToScrollTimeline(physicsTimelineOrRaw, pixelsPerUnit);
    horizontalTl = physicsTimelineToHorizontalScrollTimeline(physicsTimelineOrRaw, pixelsPerUnit);
  }

  const scrollTl = addIdleHoldKeyframes(mergeScrollTimelines(verticalTl, horizontalTl));
  const lastPhysicsMs = scrollTl.length > 0 ? scrollTl[scrollTl.length - 1].timeMs : 0;
  const lastV = scrollTl.length > 0 ? scrollTl[scrollTl.length - 1].scrollTop : 0;
  const lastH = scrollTl.length > 0 ? scrollTl[scrollTl.length - 1].scrollLeft : 0;

  const timeline = [];

  // Phase 1: Enter delay (idle at 0)
  if (enterDelay > 0) {
    timeline.push({ timeMs: 0, scrollTop: 0, scrollLeft: 0 });
    timeline.push({ timeMs: enterDelay, scrollTop: 0, scrollLeft: 0 });
  }

  // Phase 2: Physics (offset by enterDelay)
  for (const pt of scrollTl) {
    timeline.push({
      timeMs: enterDelay + pt.timeMs,
      scrollTop: pt.scrollTop,
      scrollLeft: pt.scrollLeft || 0,
    });
  }

  // Phase 3: hold the final position. When the loop wraps, scrollTop returns
  // instantly to the first keyframe.
  const totalMs = enterDelay + lastPhysicsMs + pause;

  timeline.push({
    timeMs: totalMs,
    scrollTop: lastV,
    scrollLeft: lastH,
  });

  return { timeline, totalMs };
}

function extendPaddedTimeline(timeline, targetTotalMs) {
  const last = timeline[timeline.length - 1];
  if (last.timeMs < targetTotalMs) {
    timeline.push({
      timeMs: targetTotalMs,
      scrollTop: last.scrollTop,
      scrollLeft: last.scrollLeft || 0,
    });
  }
}

function addIdleHoldKeyframes(timeline) {
  if (timeline.length < 2) return timeline;

  const idleGapMs = 64;
  const result = [timeline[0]];

  for (let i = 0; i < timeline.length - 1; i++) {
    const a = timeline[i];
    const b = timeline[i + 1];
    const scrollLeftA = a.scrollLeft || 0;
    const scrollLeftB = b.scrollLeft || 0;
    const hasMotion = a.scrollTop !== b.scrollTop || scrollLeftA !== scrollLeftB;
    const holdTimeMs = b.timeMs - 1;

    if (hasMotion && b.timeMs - a.timeMs > idleGapMs && holdTimeMs > a.timeMs) {
      result.push({ timeMs: holdTimeMs, scrollTop: a.scrollTop, scrollLeft: scrollLeftA });
    }

    result.push(b);
  }

  return result;
}

function buildPaddedTimelineEvents(scenario) {
  const enterDelay = scenario.enterDelayMs || 0;
  const events = [];

  for (const evt of scenario.events) {
    events.push({
      timeMs: enterDelay + evt.timeMs,
      type: evt.positive !== false ? 'scroll-down' : 'scroll-up',
    });
  }

  if (scenario.freeSpinStartMs != null) {
    events.push({ timeMs: enterDelay + scenario.freeSpinStartMs, type: 'free-spin' });
  }
  if (scenario.freeSpinEndMs != null) {
    events.push({ timeMs: enterDelay + scenario.freeSpinEndMs, type: 'free-spin-release' });
  }
  if (scenario.dragViewPressMs != null) {
    events.push({ timeMs: enterDelay + scenario.dragViewPressMs, type: 'drag-view' });
  }
  if (scenario.dragViewReleaseMs != null) {
    events.push({ timeMs: enterDelay + scenario.dragViewReleaseMs, type: 'drag-view-release' });
  }
  if (scenario.mouseMovements && scenario.mouseMovements.length > 0) {
    for (const m of scenario.mouseMovements) {
      if ((m.relX || 0) !== 0 || (m.relY || 0) !== 0) {
        events.push({ timeMs: enterDelay + m.timeMs, type: 'mouse-move' });
      }
    }
  }

  return events.sort((a, b) => a.timeMs - b.timeMs);
}

function prefersReducedMotion() {
  return window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}

